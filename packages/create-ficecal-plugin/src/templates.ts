/** Derives the plugin id (camelCase) from the package name. */
export function pluginId(opts: ScaffoldOptions): string {
  // Strip scope if present: "@acme/ficecal-plugin-foo" → "ficecal-plugin-foo"
  const base = opts.packageName.includes("/")
    ? opts.packageName.split("/")[1]!
    : opts.packageName;
  // kebab-case → camelCase
  return base.replace(/-([a-z])/g, (_, c: string) => c.toUpperCase());
}

/** Derives the directory name from the package name (last segment, no scope). */
export function dirName(packageName: string): string {
  return packageName.includes("/") ? packageName.split("/")[1]! : packageName;
}

