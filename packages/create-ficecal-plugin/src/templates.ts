  it("has correct id", () => {
    expect(plugin.id).toBe("${opts.packageName}");
  });

  it("has non-empty name", () => {
    expect(plugin.name.length).toBeGreaterThan(0);
  });

  it("has non-empty version", () => {
    expect(plugin.version).toBeDefined();
  });

  it("has contributions object", () => {
    expect(plugin.contributions).toBeDefined();
  });
