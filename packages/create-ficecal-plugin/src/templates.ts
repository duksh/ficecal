// ---------------------------------------------------------------------------

/**
 * Returns the complete list of files to scaffold for the given options.
 * Pure function — no file I/O.
 */
export function buildScaffoldFiles(opts: ScaffoldOptions): ScaffoldFile[] {
  const files: ScaffoldFile[] = [
    { path: "package.json",     content: packageJsonTemplate(opts) },
    { path: "tsconfig.json",    content: tsconfigTemplate() },
    { path: "README.md",        content: readmeTemplate(opts) },
    { path: "src/index.ts",     content: indexTemplate(opts) },
    { path: "tests/plugin.test.ts", content: testTemplate(opts) },
  ];

  if (opts.pluginType === "billing" || opts.pluginType === "full") {
    files.push({ path: "src/billing-adapter.ts", content: billingAdapterTemplate(opts) });
  }

  if (opts.pluginType === "theme" || opts.pluginType === "full") {
    files.push({ path: "src/theme.ts", content: themeTemplate(opts) });
  }

  if (opts.pluginType === "mcp" || opts.pluginType === "full") {
    files.push({ path: "src/mcp-tool.ts", content: mcpToolTemplate(opts) });
  }

  return files;
}
