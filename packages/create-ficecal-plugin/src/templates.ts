// ---------------------------------------------------------------------------
// src/index.ts — varies by plugin type
// ---------------------------------------------------------------------------

export function indexTemplate(opts: ScaffoldOptions): string {
  const id = pluginId(opts);
  const parts: string[] = [];

  parts.push(`// ─── ${opts.displayName} ─────────────────────────────────────────────────────`);
  parts.push(`//`);
  parts.push(`// FiceCal v2 community plugin.`);
  parts.push(`// Generated by create-ficecal-plugin.`);
  parts.push(``);
  parts.push(`import type { FicecalPlugin } from "@ficecal/plugin-api";`);

  if (opts.pluginType === "billing" || opts.pluginType === "full") {
    parts.push(`import { billingAdapterContribution } from "./billing-adapter.js";`);
  }
  if (opts.pluginType === "theme" || opts.pluginType === "full") {
    parts.push(`import { themeContribution } from "./theme.js";`);
  }
  if (opts.pluginType === "mcp" || opts.pluginType === "full") {
    parts.push(`import { mcpToolContribution } from "./mcp-tool.js";`);
  }

  parts.push(``);
  parts.push(`export const plugin: FicecalPlugin = {`);
  parts.push(`  id: "${opts.packageName}",`);
  parts.push(`  name: "${opts.displayName}",`);
  parts.push(`  version: "0.1.0",`);
  parts.push(`  description: "${opts.description}",`);
  parts.push(`  author: "${opts.author}",`);
  parts.push(`  license: "${opts.license}",`);

  // contributions
  const contributions: string[] = [];
  if (opts.pluginType === "billing" || opts.pluginType === "full") {
    contributions.push(`    billingAdapters: [billingAdapterContribution],`);
  }
  if (opts.pluginType === "theme" || opts.pluginType === "full") {
    contributions.push(`    themes: [themeContribution],`);
  }
  if (opts.pluginType === "mcp" || opts.pluginType === "full") {
    contributions.push(`    mcpTools: [mcpToolContribution],`);
  }

  if (contributions.length > 0) {
    parts.push(`  contributions: {`);
    parts.push(...contributions);
    parts.push(`  },`);
  } else {
    parts.push(`  contributions: {},`);
  }

  parts.push(`};`);
  parts.push(``);
  parts.push(`export default plugin;`);

  return parts.join("\n");
}

